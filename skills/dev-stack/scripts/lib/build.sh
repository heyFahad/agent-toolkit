#!/bin/bash
# Node version lookup, each service's command, and the process-compose config.
DS_LIB=${DS_LIB:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)}
# shellcheck source-path=SCRIPTDIR source=common.sh
. "$DS_LIB/common.sh"

# ds_node_bin <dir> <node_field>: the nvm bin directory for that Node version.
ds_node_bin() {
  local dir=$1 v=$2
  if [ "$v" = nvmrc ]; then
    [ -f "$dir/.nvmrc" ] || ds_die 2 "$dir/.nvmrc not found"
    v=$(tr -d '[:space:]' < "$dir/.nvmrc")
  fi
  local nvm=${NVM_DIR:-$HOME/.nvm} spec=$v best installed version
  # nvm aliases (lts/iron, default, ...) are files holding a version or another alias.
  for _ in 1 2 3; do [ -f "$nvm/alias/$v" ] && v=$(tr -d '[:space:]' < "$nvm/alias/$v"); done
  v=${v#v}
  if [ ! -d "$nvm/versions/node/v$v/bin" ] && [[ $v =~ ^[0-9]+(\.[0-9]+)?$ ]]; then
    # A partial version (22, 22.16): the newest installed match.
    best=$(
      for installed in "$nvm/versions/node/v$v."*; do
        [ -d "$installed/bin" ] || continue
        version=${installed##*/v}
        [[ $version =~ ^[0-9]+(\.[0-9]+)+$ ]] && printf '%s\n' "$version"
      done | sort -t. -k1,1n -k2,2n -k3,3n | tail -1
    )
    [ -n "$best" ] && v=$best
  fi
  local bin="$nvm/versions/node/v$v/bin"
  [ -d "$bin" ] || ds_die 3 "Node $spec isn't installed: run nvm install $spec"
  echo "$bin"
}

# ds_command <registry_json_file> <svc> <dir>: the shell command that runs <svc>
# from <dir>. env overrides go after doppler run, so they win over Doppler values.
ds_command() {
  local file=$1 svc=$2 dir=$3 s node_bin out k
  s=$(jq -c --arg s "$svc" '.services[$s]' "$file")
  node_bin=$(ds_node_bin "$dir" "$(jq -r .node <<<"$s")") || exit $?
  out="export PATH=$(printf %q "$node_bin"):\"\$PATH\";"
  if [ "$(jq -r '.doppler | type' <<<"$s")" = object ]; then
    local p c
    p=$(jq -r .doppler.project <<<"$s"); c=$(jq -r .doppler.config <<<"$s")
    out+=" export DOPPLER_PROJECT=$(printf %q "$p") DOPPLER_CONFIG=$(printf %q "$c");"
    out+=" exec doppler run --project $(printf %q "$p") --config $(printf %q "$c") -- env"
  else
    out+=" exec env"
  fi
  while IFS= read -r k; do
    [ -n "$k" ] || continue
    out+=" $(printf %q "$k=$(jq -r --arg k "$k" '.env[$k]' <<<"$s")")"
  done < <(jq -r '.env // {} | keys[]' <<<"$s")
  out+=" bash -c $(printf %q "$(jq -r .command <<<"$s")")"
  echo "$out"
}

# ds_service_dir <registry_json_file> <state_dir> <svc>: where <svc> runs from.
ds_service_dir() {
  local owner
  owner=$(jq -r --arg s "$3" '.[$s] // empty' "$2/owners.json" 2>/dev/null)
  if [ -n "$owner" ]; then echo "$owner"; return; fi
  jq -r --arg s "$3" '._root + "/" + .services[$s].repo' "$1"
}

# shellcheck disable=SC2016 # a jq program, not shell
_DS_PC='
def probe($s):
  if $s.health == "tcp" then {exec: {command: "nc -z localhost \($s.port)"}}
  else ($s.health | capture("^http://(?<host>[^:/?#]+)(:(?<port>[0-9]+))?(?<path>[/?][^#]*)?$")) as $u
    | {http_get: {scheme: "http", host: $u.host, port: (($u.port // "80") | tonumber),
                  path: ($u.path // "/" | if startswith("?") then "/" + . else . end)}}
  end
  + {initial_delay_seconds: 2, period_seconds: 2, timeout_seconds: 2,
     failure_threshold: ((($s.timeout // 120) / 2) | ceil)};
{version: "0.5",
 processes: (.services | to_entries | map(.key as $n | .value as $s | {key: $n, value: {
   command: $cmds[$n], working_dir: $dirs[$n], disabled: true,
   environment: ["DEVSTACK_REV=\($revs[$n])"],
   log_location: "\($state)/logs/\($n).log",
   log_configuration: {flush_each_line: true, disable_json: true, no_color: true, no_metadata: true, fields_order: ["message"]},
   availability: {restart: "on_failure", max_restarts: 3},
   depends_on: (($s.depends_on // []) | map({key: ., value: {condition: "process_healthy"}}) | from_entries),
   readiness_probe: probe($s)}}) | from_entries)}
'

# ds_pc_config <registry_json_file> <state_dir>: write <state_dir>/process-compose.yaml.
# A service whose command can't be built (say, its Node isn't installed) gets a
# launcher that prints why and exits 1; `up` reports that error up front when
# the service is asked for.
ds_pc_config() {
  local file=$1 state=$2 svc dir cmd err cmds='{}' dirs='{}' revs='{}' launcher
  mkdir -p "$state/logs" "$state/run"
  while IFS= read -r svc; do
    dir=$(ds_service_dir "$file" "$state" "$svc")
    dirs=$(jq -c --arg k "$svc" --arg v "$dir" '. + {($k): $v}' <<<"$dirs")
    launcher="$state/run/$svc.sh"
    # The command lives in a launcher script: process-compose's YAML parser
    # rejects shell escapes, and the script can be run by hand to debug.
    if cmd=$( (ds_command "$file" "$svc" "$dir") 2>"$state/run/.err"); then
      printf '#!/bin/bash\n# Generated by devstack for %s. Do not edit.\n%s\n' "$svc" "$cmd" > "$launcher"
    else
      # Never leave a service out: process-compose would stop a running copy.
      err=$(sed 's/^devstack: //' "$state/run/.err")
      printf '#!/bin/bash\n# Generated by devstack for %s. Do not edit.\necho %q >&2\nexit 1\n' "$svc" "devstack: $err" > "$launcher"
    fi
    cmds=$(jq -c --arg k "$svc" --arg v "exec bash $(printf %q "$launcher")" '. + {($k): $v}' <<<"$cmds")
    # The revision changes whenever the launcher does, so process-compose sees
    # a new definition and the next up restarts the service.
    revs=$(jq -c --arg k "$svc" --arg v "$(_ds_sha256 "$launcher" | cut -c1-16)" '. + {($k): $v}' <<<"$revs")
  done < <(jq -r '.services | keys[]' "$file")
  rm -f "$state/run/.err"
  jq --argjson cmds "$cmds" --argjson dirs "$dirs" --argjson revs "$revs" --arg state "$state" "$_DS_PC" "$file" \
    > "$state/process-compose.yaml.tmp" && mv "$state/process-compose.yaml.tmp" "$state/process-compose.yaml"
}
